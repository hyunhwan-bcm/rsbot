"""Generate src/bin/mem1_check.rs: a replay of recorded store_replies calls against the port (MEM1).

    python3 harness/mem1_gen_check.py

Reads the `pub fn` signatures of src/memory/store_replies.rs and writes one dispatch arm per
Python function whose parameter types the replay knows how to build from the recorded JSON.
Run the checker with `./target/fast/mem1_check CALLS.jsonl.gz [--show N] [--fn NAME]`.
"""
import ast, re

SRC = "src/memory/store_replies.rs"
PY = "../upstream/pybot/bot/memory/store_replies.py"
OUT = "src/bin/mem1_check.rs"

src = open(SRC).read()
py_names = {n.name for n in ast.parse(open(PY).read()).body if isinstance(n, ast.FunctionDef)}
sigs = {}
for name, args, ret in re.findall(r"^pub fn (\w+)\((.*?)\)(?: -> ([^{]+?))? \{", src, re.M | re.S):
    params = []
    depth = 0
    cur = ""
    for ch in args:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            params.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        params.append(cur.strip())
    sigs[name] = ([p.split(":", 1)[1].strip() for p in params], (ret or "()").strip())

BUILD = {
    "&str": "&s(a, {i})",
    "Option<&str>": "os(a, {i}).as_deref()",
    "bool": "b(a, {i})",
    "i64": "n(a, {i})",
    "usize": "n(a, {i}) as usize",
    "&Value": "&v(a, {i})",
    "&[String]": "&ss(a, {i})",
    "&[Value]": "&vs(a, {i})",
    "&HashSet<String>": "&hs(a, {i})",
    "&[Turn]": "&turns(a, {i})",
    "&Turn": "&turns_one(a, {i})",
    "&Portion": "&portion(a, {i})",
    "&[Move]": "&moves(a, {i})",
    "&[(String, Value)]": "&pairs(a, {i})",
    "&Memory": "&mem",
    "&mut Memory": "&mut mem",
    "Option<&Memory>": "Some(&mem)",
    "Option<&mut Memory>": "Some(&mut mem)",
}

arms = []
skipped = []
for name in sorted(py_names):
    if name not in sigs:
        skipped.append((name, "no rust fn"))
        continue
    params, ret = sigs[name]
    built = []
    ok = True
    for i, t in enumerate(params):
        if t not in BUILD:
            ok = False
            break
        built.append(BUILD[t].format(i=i))
    if not ok or ret in ("Re", "&'static [String]") or "fn(" in " ".join(params):
        skipped.append((name, "types"))
        continue
    call = f"sr::{name}({', '.join(built)})"
    has_mem = any("Memory" in t for t in params)
    m_variant = sigs.get(name + "_m")
    if m_variant and has_mem:
        # Python's memory=None: the port's `_m` twin takes the memory as an Option.
        mp, _ = m_variant
        mbuilt = []
        for i, t in enumerate(mp):
            if t in ("Option<&Memory>", "Option<&mut Memory>"):
                mbuilt.append("None")
            else:
                mbuilt.append(BUILD[t].format(i=i))
        none_call = f"sr::{name}_m({', '.join(mbuilt)})"
        arms.append(f'        "{name}" => if none {{ out(&{none_call}) }} else {{ out(&{call}) }},')
    else:
        arms.append(f'        "{name}" => out(&{call}),')

