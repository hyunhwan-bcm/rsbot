"""Generate src/bin/com1_check.rs: replay calls recorded by harness/com1_calls.py against the Rust
ports of bot/compose/fallback.py, own_facts.py and why.py, function by function.

    python3 harness/gen_com1_check.py        # rewrites src/bin/com1_check.rs from the signatures

A function whose parameter or return type the replay cannot build is left out (it is listed in
the generated file's header).
"""
import os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FILES = {"bot.compose.fallback": "src/compose/fallback.rs",
         "bot.compose.own_facts": "src/compose/own_facts.rs",
         "bot.compose.why": "src/compose/why.rs"}

PARAM = {
    "&str": ("let {v} = sv(&a[{i}]);", "&{v}"),
    "&Memory": ("let {v} = mem(&a[{i}]);", "&{v}"),
    "&mut Memory": ("let mut {v} = mem(&a[{i}]);", "&mut {v}"),
    "&[String]": ("let {v} = strs(&a[{i}]);", "&{v}"),
    "Option<&[String]>": ("let {v} = opt_strs(&a[{i}]);", "{v}.as_deref()"),
    "bool": ("let {v} = truthy(&a[{i}]);", "{v}"),
    "i64": ("let {v} = a[{i}].as_i64().unwrap_or(0);", "{v}"),
    "usize": ("let {v} = a[{i}].as_u64().unwrap_or(0) as usize;", "{v}"),
    "&Value": ("let {v} = Value::from_plain(&a[{i}]);", "&{v}"),
    "&Understood": ("let {v} = und(&a[{i}])?;", "&{v}"),
    "Option<&Understood>": ("let {v} = opt_und(&a[{i}])?;", "{v}.as_ref()"),
    "Option<&str>": ("let {v} = opt_s(&a[{i}]);", "{v}.as_deref()"),
    "&[Turn]": ("let {v} = turns(&a[{i}]);", "&{v}"),
    # a turn dict, with Python's `{}` (or None) for "no turn"
    "Option<&Turn>": ("let {v} = one_turn(&a[{i}]);", "{v}.as_ref()"),
}
RET = {"bool", "String", "Option<String>", "Vec<String>", "Option<Vec<String>>", "HashSet<String>",
       "Value", "i64", "Option<bool>", "", "Vec<(String, String)>", "Option<i64>", "usize",
       "(Option<String>, String)", "Vec<Vec<String>>", "Option<(String, String)>",
       "Option<&Turn>"}


def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def main():
    arms, skipped = [], []
    for mod, path in FILES.items():
        src = open(os.path.join(ROOT, path)).read()
        rust_mod = path[len("src/"):-len(".rs")].replace("/", "::")
        for m in re.finditer(r"^pub fn ([A-Za-z_0-9]+)(<[^>]*>)?\((.*?)\)\s*(?:->\s*(.*?))?\s*\{", src, re.M | re.S):
            name, generics, params, ret = m.group(1), m.group(2), m.group(3), (m.group(4) or "").strip()
            body_start = m.end()
            if "unported!" in src[body_start:body_start + 200]:
                continue
            ps = split_params(params)
            lines, call = [], []
            ok = not generics
            for i, p in enumerate(ps):
                pname, _, ptype = p.partition(":")
                ptype = " ".join(ptype.split())
                if ptype not in PARAM:
                    ok = False
                    break
                let, use = PARAM[ptype]
                v = f"p{i}"
                lines.append(let.format(v=v, i=i))
                call.append(use.format(v=v))
            if ret not in RET:
                ok = False
            if not ok:
                skipped.append(f"{mod}:{name}")
                continue
            body = " ".join(lines)
            arms.append(
                f'        "{mod}:{name}" => {{ if a.len() != {len(ps)} {{ return None; }} {body} '
                f'Some(J::j(&crate_::{rust_mod}::{name}({", ".join(call)}))) }}')
    out = open(os.path.join(ROOT, "src/bin/com1_check.rs"), "w")
    out.write(TEMPLATE.replace("//ARMS", "\n".join(arms)).replace(
        "//SKIPPED", "\n".join(f"//   {s}" for s in skipped)))
    print(f"{len(arms)} functions in the replay, {len(skipped)} left out")


