"""COM5: run each case in PyBot and write the answers into the Rust files as #[cfg(test)] tests.

    python3 harness/com5_cases.py harness/com5_spec.py src/compose

A case is {"m": module (under bot.compose), "f": function, "a": python args ("$mem" is the
memory), "mem": [[user, bot, module], ...] or null, "rs": the Rust call ({mem} is the memory),
"k": what the Rust call gives back: bool | str | opt_str | opt_pool | value}. Each module's tests
are written between the COM5-CASES markers at the end of src/compose/<module>.rs.
"""
