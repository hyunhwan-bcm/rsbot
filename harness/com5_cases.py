BEGIN = "// ---- COM5-CASES (generated by harness/com5_cases.py; expected values from PyBot) ----"


def rs_str(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif ord(c) < 32:
            out.append("\\u{%x}" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def memory_of(turns):
    if turns is None:
        return {}
    return {"turns": [{"user": u, "bot": b, "module": m or None} for u, b, m in turns]}


def rs_mem(turns):
    if not turns:
        return "&Memory::new()"
    return "&mem(&[" + ", ".join("(%s, %s, %s)" % (rs_str(u), rs_str(b), rs_str(m or "")) for u, b, m in turns) + "])"


def want(kind, res):
    if kind == "bool":
        return "true" if res else "false"
    if kind == "str":
        return rs_str(res if res is not None else "") + ".to_string()"
    if kind == "opt_str":
        return "None" if res is None else "Some(%s.to_string())" % rs_str(res)
    if kind == "opt_pool":
        return "None" if res is None else "Some(vec![%s])" % ", ".join(rs_str(x) + ".to_string()" for x in res)
    raise ValueError(kind)


def main():
    if sys.argv[1].endswith(".py"):
        import runpy
        cases = runpy.run_path(sys.argv[1])["CASES"]
    else:
        cases = json.load(open(sys.argv[1]))
    src = sys.argv[2]
    by_mod = {}
    for c in cases:
        mod = importlib.import_module("bot.compose." + c["m"])
        mem = memory_of(c.get("mem"))
        args = [mem if a == "$mem" else a for a in c["a"]]
        random.seed(0)
        try:
            res, raised = getattr(mod, c["f"])(*args), None
        except Exception as e:  # noqa: BLE001
            res, raised = None, type(e).__name__
        expr = c["rs"].replace("{mem}", rs_mem(c.get("mem")))
        if raised:
            body = "    assert!(raises(|| %s));" % expr
        else:
            body = "    if let Some(got) = unless_unported(|| %s) {\n        assert_eq!(got, %s);\n    }" % (expr, want(c["k"], res))
        by_mod.setdefault(c["m"], []).append(body)
    for m, bodies in by_mod.items():
        path = os.path.join(src, m + ".rs")
        code = open(path).read()
        if BEGIN in code:
            code = code[:code.index(BEGIN)].rstrip() + "\n"
        tests = "\n".join("#[test]\nfn case_%d() {\n%s\n}\n" % (i, b) for i, b in enumerate(bodies))
        code += "\n" + BEGIN + "\n#[cfg(test)]\nmod pybot_cases {\n" + HELPERS + "\n" + indent(tests) + "}\n"
        open(path, "w").write(code)
        print(m, len(bodies))


def indent(s):
    return "".join(("    " + l if l.strip() else l) for l in s.splitlines(True))


HELPERS = indent('''#![allow(unused_imports, dead_code)]
use super::*;
use crate::data::Value;
use crate::state::{Memory, Turn};

fn mem(turns: &[(&str, &str, &str)]) -> Memory {
    let mut m = Memory::new();
    m.turns = turns
        .iter()
        .map(|(u, b, md)| Turn { user: u.to_string(), bot: b.to_string(), module: (!md.is_empty()).then(|| md.to_string()) })
        .collect();
    m
}

/// The call's result, or None when it reached a function another workstream has not ported yet.
fn unless_unported<T>(f: impl FnOnce() -> T) -> Option<T> {
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)) {
        Ok(v) => Some(v),
        Err(e) => {
            let msg = e.downcast_ref::<String>().cloned().or_else(|| e.downcast_ref::<&str>().map(|s| s.to_string())).unwrap_or_default();
            if msg.starts_with("UNPORTED") {
                eprintln!("skipped: {msg}");
                return None;
            }
            std::panic::resume_unwind(e)
        }
    }
}

/// True when the call raises (panics), as the Python does.
fn raises<T>(f: impl FnOnce() -> T) -> bool {
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)).is_err()
}
''')

if __name__ == "__main__":
    main()
